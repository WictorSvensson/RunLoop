// Centralized Suunto Cloud API (OAuth2) configuration. Server-only values —
// the client secret must never reach the browser (only the authorize URL,
// built server-side, is exposed). Missing required vars fail closed and loud
// at call time (SESSION_SECRET pattern), never with a silent fallback.

function optional(name: string): string | undefined {
  // Trim: ids/secrets are copy-pasted from the Suunto API Zone and a
  // trailing space/quote would be sent as part of the value — Suunto
  // rejects a padded client_id with 400 invalid_request.
  const value = process.env[name]?.trim();
  return value && value.length > 0 ? value : undefined;
}

function required(name: string): string {
  const value = optional(name);
  if (!value) {
    throw new Error(
      `${name} is not set. Copy .env.example to .env and register an OAuth app in the Suunto API Zone (see lib/suunto/client.ts header).`,
    );
  }
  return value;
}

export const suuntoConfig = {
  /** Client Id auto-generated by Suunto in the OAuth app settings. */
  get clientId(): string {
    return required("SUUNTO_CLIENT_ID");
  },
  /** Client secret set in the Suunto OAuth app settings. Never client-safe. */
  get clientSecret(): string {
    return required("SUUNTO_CLIENT_SECRET");
  },
  /** Subscription key from the Developer API subscription. Sent as
   * Ocp-Apim-Subscription-Key on every data API request. */
  get subscriptionKey(): string {
    return required("SUUNTO_SUBSCRIPTION_KEY");
  },
  /** Redirect URI registered in the Suunto OAuth app settings. */
  get redirectUri(): string {
    return required("SUUNTO_REDIRECT_URI");
  },
  // Spec truth (oauth2-api.yaml + https://apizone.suunto.com/how-to-start):
  // the authorize endpoint defines NO `scope` request parameter — the
  // `workout` grant is issued by Suunto and returned in the token
  // response, so none is ever sent. There is deliberately no SUUNTO_SCOPE.
  /** OAuth host (override for testing only). The spec yaml lists
   * cloudapi.suunto.com but its own Important-notes section corrects this
   * to cloudapi-oauth.suunto.com for all OAuth calls. */
  get oauthBaseUrl(): string {
    return optional("SUUNTO_OAUTH_BASE_URL") ?? "https://cloudapi-oauth.suunto.com";
  },
  /** Data API host (override for testing only). */
  get apiBaseUrl(): string {
    return optional("SUUNTO_API_BASE_URL") ?? "https://cloudapi.suunto.com";
  },
};

// API paths, straight from the real specs (sibling Suunto-documentation/):
// - suunto-workout-api.yaml: servers https://cloudapi.suunto.com/v3/workouts
//   → list GET /v3/workouts?since=&until=&limit=&offset=
//   (&filter-by-modification-time), FIT export
//   GET /v3/workouts/{workoutIdOrKey}/fit (application/octet-stream).
// - new-247-api.yaml: servers https://cloudapi.suunto.com/247samples
//   → GET /247samples/sleep?from=&to= (epoch ms, ≤28 d window,
//   Content-Type: application/json required),
//   GET /247samples/activity and /247samples/recovery (same params;
//   recovery/Balance has no DailyCheckin column, intraday activity samples
//   are not daily-resting signals — neither is synced).
export const SUUNTO_WORKOUTS_PATH = "/v3/workouts";
export const SUUNTO_WORKOUT_FIT_PATH = (workoutKey: string): string =>
  `/v3/workouts/${encodeURIComponent(workoutKey)}/fit`;
export const SUUNTO_SLEEP_PATH = "/247samples/sleep";

